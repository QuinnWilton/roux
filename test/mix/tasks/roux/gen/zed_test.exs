defmodule Mix.Tasks.Roux.Gen.ZedTest do
  use ExUnit.Case, async: true

  @moduletag :tmp_dir

  import ExUnit.CaptureIO

  alias Mix.Tasks.Roux.Gen.Zed

  describe "gen_extension_toml/2" do
    test "generates valid extension manifest" do
      toml = Zed.gen_extension_toml("my_app", [Roux.Test.HoverLang, Roux.Test.TinyLang])

      assert toml =~ ~s|id = "my_app-lsp"|
      assert toml =~ ~s|name = "My App LSP"|
      assert toml =~ ~s|description = "Language server for My App (powered by Roux)"|
      assert toml =~ ~s|languages = ["HoverLang", "TinyLang"]|
      assert toml =~ "# Generated by mix roux.gen.zed"
    end

    test "handles single-word app name" do
      toml = Zed.gen_extension_toml("lark", [Roux.Test.TinyLang])

      assert toml =~ ~s|id = "lark-lsp"|
      assert toml =~ ~s|name = "Lark LSP"|
    end

    test "generates empty languages list when no modules given" do
      toml = Zed.gen_extension_toml("app", [])

      assert toml =~ "languages = []"
    end
  end

  describe "gen_language_toml/1" do
    test "generates config with file extensions and line comments" do
      toml = Zed.gen_language_toml(Roux.Test.HoverLang)

      assert toml =~ ~s|name = "HoverLang"|
      assert toml =~ ~s|path_suffixes = ["hover"]|
      assert toml =~ ~s|line_comments = ["# "]|
      assert toml =~ "# Generated by mix roux.gen.zed"
    end

    test "strips leading dot from file extensions" do
      toml = Zed.gen_language_toml(Roux.Test.TinyLang)

      assert toml =~ ~s|path_suffixes = ["tiny"]|
    end
  end

  describe "run/1" do
    test "generates all files in output directory", %{tmp_dir: tmp_dir} do
      output =
        capture_io(fn ->
          Zed.run(["Roux.Test.HoverLang", "Roux.Test.TinyLang", "--output", tmp_dir])
        end)

      assert output =~ "Generated Zed extension"

      # Extension manifest.
      extension_path = Path.join(tmp_dir, "extension.toml")
      assert File.exists?(extension_path)
      content = File.read!(extension_path)
      assert content =~ ~s|languages = ["HoverLang", "TinyLang"]|

      # Per-language configs.
      hover_config = Path.join([tmp_dir, "languages", "hoverlang", "config.toml"])
      assert File.exists?(hover_config)
      assert File.read!(hover_config) =~ ~s|name = "HoverLang"|

      tiny_config = Path.join([tmp_dir, "languages", "tinylang", "config.toml"])
      assert File.exists?(tiny_config)
      assert File.read!(tiny_config) =~ ~s|name = "TinyLang"|

      # Extension WASM.
      wasm_path = Path.join(tmp_dir, "extension.wasm")
      assert File.exists?(wasm_path)
    end

    test "warns with no language modules", %{tmp_dir: tmp_dir} do
      output =
        capture_io(fn ->
          Zed.run(["--output", tmp_dir])
        end)

      assert output =~ "no language modules specified"

      # Should still generate extension.toml with empty languages.
      extension_path = Path.join(tmp_dir, "extension.toml")
      assert File.exists?(extension_path)
      assert File.read!(extension_path) =~ "languages = []"
    end

    test "raises for unknown module", %{tmp_dir: tmp_dir} do
      assert_raise Mix.Error, ~r/could not load module/, fn ->
        Zed.run(["NonExistentModule", "--output", tmp_dir])
      end
    end

    test "raises for module that is not a Roux.Lang", %{tmp_dir: tmp_dir} do
      assert_raise Mix.Error, ~r/does not implement the Roux.Lang behaviour/, fn ->
        Zed.run(["Enum", "--output", tmp_dir])
      end
    end
  end
end
